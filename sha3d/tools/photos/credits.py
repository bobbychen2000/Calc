"""B3 Fix round 1: write docs/phase1/photos_credits.md, the credits list that goes beside photos_contact_sheet.jpg.

For every photo on the sheet: title, author, licence with its URL, the Commons file page, and the modification made.
Reads the per-file Commons metadata (SOURCES.json beside the photos, from the Commons API) and tools/photos/subjects.json.

usage: python3 -I sha3d/tools/photos/credits.py PHOTO_DIR OUT.md [subjects.json]
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from commons_meta import clean_author, clean_date   # noqa: E402

d, outp = sys.argv[1], sys.argv[2]
subj = json.load(open(sys.argv[3], encoding='utf-8')) if len(sys.argv) > 3 else {}
S = json.load(open(os.path.join(d, 'SOURCES.json'), encoding='utf-8'))
MOD = 'scaled down to fit a 400 × 300 px tile (whole frame, not cropped); caption added below'


def lic(r):
    if r['licence'] == 'Public domain':
        return f"Public domain (release on the [file page]({r['page_url']}); no attribution required, credited anyway)"
    u = (r.get('licence_url') or '').rstrip('/') + '/'
    return f"[{r['licence']}]({u})"


rows, left = [], []
for r in S['files']:
    num = r['file'][:2]
    title = r['title'][5:]
    a = clean_author(r['author']).replace('|', '/')
    if r['reuse_in_repo'] != 'yes' or num == '06':
        left.append((num, title, a, r['licence']))
        continue
    rows.append(f"| {num} | {subj.get(num, '')} | [{title}]({r['page_url']}) | {a} | {lic(r)} | "
                f"{clean_date(r['date'], title)} | {MOD} |")
out = ['# Photo credits for `photos_contact_sheet.jpg`', '',
       'Task B3, Phase 1, Fix round 1 (2026-11-14). The contact sheet `docs/phase1/photos_contact_sheet.jpg` is a '
       'compilation of the 23 Wikimedia Commons photos below. Each photo is the work of its author and is used under '
       'the licence shown. The licence and author of every file were read from the Commons API (`extmetadata`: '
       'LicenseShortName, LicenseUrl, Artist) on 2026-11-14 and re-checked by C2 the same day (25 of 25 matched).', '',
       '**Modifications.** Every photo is a 1280 px Commons rendition, scaled down to fit a 400 × 300 px tile. The whole '
       'frame is kept (nothing is cropped). We added a caption strip under each tile (number, our subject line, author, '
       'licence, date, Commons title). No other change was made.', '',
       '**Licence of the compilation.** The contact sheet as a whole is released under '
       '[CC BY-SA 4.0](https://creativecommons.org/licenses/by-sa/4.0/). The CC BY-SA 3.0 photos may be included, because '
       'CC BY-SA 3.0 allows adaptations under a later version of the licence. The CC BY 4.0 and public-domain photos keep '
       'their own terms. No endorsement by any author is implied.', '',
       '| No. | Subject (ours) | Title (Commons file page) | Author | Licence | Date | Modification |',
       '|---|---|---|---|---|---|---|'] + rows + ['',
       '**Not on the sheet** (kept local, reference only):', '']
for num, title, a, l in left:
    why = 'identifiable people (privacy)' if num == '06' else 'GFDL 1.2 only, not compatible with the CC BY-SA compilation'
    out.append(f'- {num}: "{title}", {a}, {l}: {why}.')
out += ['', 'Generated by `tools/photos/credits.py` from the Commons metadata in '
        '`refs/cache/photos/commons/SOURCES.json` (local) and `tools/photos/subjects.json`.', '']
open(outp, 'w', encoding='utf-8').write('\n'.join(out))
print('wrote', outp, len(rows), 'credits')
