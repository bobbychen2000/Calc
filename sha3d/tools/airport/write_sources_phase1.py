def entry(f, what, gen, attr, lic):
    p = os.path.join(D1, f)
    b = open(p, 'rb').read()
    return f, {'what': what, 'generator': gen, 'attribution': attr, 'licence': '; '.join(lic),
               'bytes': len(b), 'sha256': hashlib.sha256(b).hexdigest()}


