#!/usr/bin/env python3
"""FAA ACD dimensions of every fixed-wing type -> hwd3d/js/aircraft/ga_acd.js (the data module of js/aircraft/ga_dims.js).

New file for hwd3d Phase 2 (P3, traffic). js/aircraft/ga_dims.js holds the rules (type -> placeholder class, planform
proportions, helicopter and unknown-type defaults); this script only writes the published numbers it reads, so every
dimension the engine and the placeholders use names its source row.

Input (read only, never modified):
  sfo3d/refs/cache/faa/faa_aircraft_char_database.xlsx - FAA Aircraft Characteristics Data, October 2024 (modified
  2025-01-03; sha256 3e68848b...; https://www.faa.gov/airports/engineering/aircraft_char_database/aircraft_data;
  US Government work, public domain). Read with hwd3d/tools/types/build_ga_types.py read_acd (the zipped-XML reader of
  Phase 1; that file is frozen and only imported here). Every row is written (388 in this edition), not only the 67 HWD
  on-field types of data/ga_types.json: the engine also draws overflights (OAK / SFO airliners) and itinerant bizjets.
  The ACD has no helicopter rows; helicopter sizes are ga_dims.js defaults marked inferred.
  hwd3d/data/ga_types.json - only to check that each of its obs rows agrees with this export (same row, same values).

Output row: ICAO -> [length_m, span_m (without winglets), span_with_winglets_m, tail_height_m, mtow_kg, engine class,
engines, ACD row, "Manufacturer Model_FAA"]; m = ft x 0.3048, kg = lb x 0.45359237 (exact), rounded to 1 mm / 0.1 kg.
A designator matches ICAO_Code first; FAA_Designator rows are added under their FAA designator only where no ICAO_Code
row has that name (ACD rows can share an ICAO code: the first row wins and the others are listed in `dups`).
usage: python3 -I hwd3d/tools/traffic/build_ga_dims.py
"""
import hashlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
HWD = os.path.normpath(os.path.join(HERE, '..', '..'))
REPO = os.path.dirname(HWD)
sys.path.insert(0, os.path.join(HWD, 'tools', 'types'))
import build_ga_types as BT  # noqa: E402  (frozen Phase 1 reader: read_acd, num, FT, LB)

OUT = os.path.join(HWD, 'js', 'aircraft', 'ga_acd.js')


def main():
    rows, _dd, meta = BT.read_acd(BT.XLSX)
    sha = hashlib.sha256(open(BT.XLSX, 'rb').read()).hexdigest()
    by = {}; dups = {}; fixed = 0
    def rec(n, r):
        f = lambda k: BT.num(r.get(k))
        L, s, sw, H, m = f('Length_ft'), f('Wingspan_ft_without_winglets_sharklets'), f('Wingspan_ft_with_winglets_sharklets'), f('Tail_Height_at_OEW_ft'), f('MTOW_lb')
        ft = lambda v: None if v is None else round(v * BT.FT, 3)
        return [ft(L), ft(s), ft(sw), ft(H), None if m is None else round(m * BT.LB, 1), r.get('Physical_Class_Engine'),
                int(BT.num(r.get('Num_Engines'))) if BT.num(r.get('Num_Engines')) else None, n,
                ' '.join(x for x in (r.get('Manufacturer'), r.get('Model_FAA')) if x)]
    for n, r in rows:
        if (r.get('Class') or '') not in ('Fixed-wing', 'Amphibian'): continue
        k = (r.get('ICAO_Code') or '').strip().upper()
        if not k or k in ('N/A', 'TBD'): continue
        if k in by: dups.setdefault(k, []).append(n); continue
        by[k] = rec(n, r)
    for n, r in rows:
        if (r.get('Class') or '') not in ('Fixed-wing', 'Amphibian'): continue
        k = (r.get('FAA_Designator') or '').strip().upper()
        if k and k not in ('N/A', 'TBD') and k not in by: by[k] = rec(n, r); fixed += 1
    # cross-check against the Phase 1 file
    G = json.load(open(os.path.join(HWD, 'data', 'ga_types.json')))['types']
    bad = []
    for t, v in G.items():
        if v.get('src') != 'obs': continue
        e = by.get(t)
        if not e or e[7] != v['acd_row'] or abs((e[0] or 0) - (v['length_m'] or 0)) > 1e-3 or abs((e[1] or 0) - (v['wingspan_m'] or 0)) > 1e-3:
            bad.append(t)
    assert not bad, bad
    body = json.dumps(dict(sorted(by.items())), separators=(',', ':'), ensure_ascii=False)
    hdr = ('// generated by tools/traffic/build_ga_dims.py - do not edit. FAA Aircraft Characteristics Data (%s, modified %s;\n'
           '// sfo3d/refs/cache/faa/faa_aircraft_char_database.xlsx sha256 %s; U.S. Government work, public domain).\n'
           '// ICAO -> [length_m, span_m (no winglets), span_winglets_m, tail_height_m (OEW), mtow_kg, engine class, engines, ACD row,\n'
           '// "Manufacturer Model_FAA"]; ft x 0.3048, lb x 0.45359237. %d designators (%d via FAA_Designator); fixed-wing and\n'
           '// amphibian rows only (this ACD edition has no helicopter rows). Checked against data/ga_types.json (%d obs rows agree).\n'
           % (meta['title'], meta['modified'], sha, len(by), fixed, sum(1 for v in G.values() if v.get('src') == 'obs')))
    open(OUT, 'w').write(hdr + 'export const ACD_SOURCE = %s;\n' % json.dumps({'title': meta['title'], 'modified': meta['modified'], 'sha256': sha,
        'url': 'https://www.faa.gov/airports/engineering/aircraft_char_database/aircraft_data', 'licence': 'US Government work (public domain)', 'dups': dups})
        + 'export const ACD = ' + body + ';\n')
    print('wrote', OUT, len(by), 'types', os.path.getsize(OUT), 'bytes; dup ICAO rows', len(dups))


if __name__ == '__main__':
    main()
