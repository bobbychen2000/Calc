// unknown type: a stand-in by emitter category [inf]; the stand-in's ACD dimensions are used, the record says so
const CAT_STAND_IN = { A1: 'C172', A2: 'C56X', A3: 'B738', A4: 'B752', A5: 'B763', A6: 'C56X', B1: null, B4: null };

const cache = new Map();
const r3 = (v) => Math.round(v * 1000) / 1000;

function acdRow(t) { const a = t && ACD[t]; if (!a) return null; return { L: a[0], span: a[1] ?? a[2], spanWl: a[2], H: a[3], mtow: a[4], eng: a[5], n: a[6], row: a[7], name: a[8] }; }

// -> { cls, sub, src, basis }   cls: single_hw | single_lw | twin | turboprop | jet | heli | glider | ultralight | unknown
// sub: jet -> light (MTOW <= 5,700 kg) | biz (<= 50 t) | airliner; turboprop -> single | twin; twin -> piston
export function classOf(t, category) {
  t = t ? String(t).toUpperCase() : null;
  if ((t && HELI_TYPES.has(t)) || category === 'A7') return { cls: 'heli', sub: null, src: category === 'A7' ? 'obs' : 'inf', basis: category === 'A7' ? 'emitter category A7 (rotorcraft)' : 'type in HELI_TYPES (Phase 1 list)' };
  const a = acdRow(t);
  if (a && a.eng) {
    const n = a.n || 1;
    if (a.eng === 'Piston') {
      if (n >= 2) return { cls: 'twin', sub: 'piston', src: 'obs', basis: `FAA ACD row ${a.row}: piston, ${n} engines` };
      const hw = HIGH_WING.has(t);
      return { cls: hw ? 'single_hw' : 'single_lw', sub: null, src: 'inf', basis: `FAA ACD row ${a.row}: piston single (obs); ${hw ? 'high' : 'low'} wing by the family table [inf]` };
    }
    if (a.eng === 'Turboprop') return { cls: 'turboprop', sub: n >= 2 ? 'twin' : 'single', src: 'obs', basis: `FAA ACD row ${a.row}: turboprop, ${n} engine${n > 1 ? 's' : ''}` };
    if (a.eng === 'Jet') {
      const sub = a.mtow != null && a.mtow <= 5700 ? 'light' : a.mtow != null && a.mtow <= 50000 ? 'biz' : 'airliner';
      return { cls: 'jet', sub, src: 'obs', basis: `FAA ACD row ${a.row}: jet, MTOW ${a.mtow} kg -> ${sub} (cut-offs 5,700 kg / 50 t [inf])` };
    }
  }
  if (category === 'B1') return { cls: 'glider', sub: null, src: 'obs', basis: 'emitter category B1' };
  if (category === 'B4') return { cls: 'ultralight', sub: null, src: 'obs', basis: 'emitter category B4' };
  if (t) { // a designator without an ACD row (homebuilts: RV4, LGEZ, GLAS, PTS1, ST75 ...): a light single [inf]
    const hw = HIGH_WING.has(t);
    return { cls: hw ? 'single_hw' : 'single_lw', sub: null, src: 'inf', basis: `no FAA ACD row for ${t}: light ${hw ? 'high' : 'low'}-wing single assumed [inf]` };
  }
  return { cls: 'unknown', sub: null, src: 'inf', basis: category ? `no type; emitter category ${category}` : 'no type, no category' };
}

