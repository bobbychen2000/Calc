const TAIL_GEAR = { main: 0.18, tail: 0.94 };   // tail-wheel layout: main wheels ahead of the CG, tail wheel near the tail [inf]

function finish(d, P) {
  const L = d.L, span = d.span;
  d.R = r3(Math.min(2.2, Math.max(0.42, P.rFac * L + 0.08)));
  d.Hc = r3(d.R + 0.16 * (d.H || 2.7));
  const rootC = span * P.chord * 1.2, tipC = rootC * P.taper;
  d.wing = { span, rootLE: r3(P.le * L), rootC: r3(rootC), tipC: r3(tipC), sweep: P.sweep, pos: P.pos, dihedral: P.dih };
  d.hstab = { x: r3(L * (1 - P.hsC) - 0.1), span: r3(span * P.hsSpan), rootC: r3(P.hsC * L) };
  if (d.gearKind === 'tail') { d.xMain = r3(TAIL_GEAR.main * L + d.wing.rootLE * 0.4); d.xNose = r3(TAIL_GEAR.tail * L); }
  else { d.xMain = r3(P.main * L); d.xNose = r3(P.nose * L); }
  if (d.track == null) d.track = r3(Math.max(1.6, P.track * span));
  d.ant = r3(P.ant * L);
  return d;
}

export function gaDims(icaoType, category = null) {
  const t = icaoType ? String(icaoType).toUpperCase() : null; const cat = category || null;
  const key = (t || '-') + '|' + (cat || '-'); if (cache.has(key)) return cache.get(key);
  const C = classOf(t, cat); const prov = [C.basis];
  let d;
  if (C.cls === 'heli') {
    const h = HELI[t] || HELI[HELI_DEFAULT];
    const [rotor, L, H] = h;
    d = { type: t, name: t ? `${t} (helicopter)` : 'Helicopter', cls: 'heli', sub: null, engines: 1, engType: null, L, span: rotor, H, rotor, mtow_kg: null,
      gearKind: 'skid', retract: false, tail: 'conv',
      src: 'inf', basis: HELI[t] ? HELI_BASIS : `type ${t || 'unknown'} not in the table: ${HELI_DEFAULT} figures used [inf]` };
    d.R = r3(0.06 * L + 0.15); d.Hc = r3(d.R + 0.45);
    d.track = r3(Math.max(1.9, 0.22 * rotor));            // skid track [inf]
    d.xMain = r3(0.32 * L); d.xNose = r3(0.32 * L);         // skid centre under the mast (local origin) [inf]
    d.skidLen = r3(0.30 * L);
    d.wing = null; d.hstab = { x: r3(L * 0.86), span: r3(0.2 * rotor), rootC: r3(0.05 * L) };
    d.ant = r3(0.30 * L);
    d.dimSrc = { L: 'inf', span: 'inf', H: 'inf', rotor: 'inf', track: 'inf', proportions: 'inf' };
    prov.push(d.basis);
  } else {
    let a = acdRow(t), stand = null;
    let cls = C.cls, sub = C.sub;
    if (!a) {   // no ACD row: a stand-in by category (unknown type) or a light single (designator without a row)
      stand = C.cls === 'unknown' ? (CAT_STAND_IN[cat] || 'C172') : (C.cls === 'single_hw' ? 'C172' : 'P28A');
      if (C.cls === 'glider' || C.cls === 'ultralight') stand = 'C152';
      a = acdRow(stand);
      if (C.cls === 'unknown') { const S = classOf(stand, null); cls = S.cls; sub = S.sub; }
      prov.push(`dimensions of the stand-in ${stand} (FAA ACD row ${a.row}) [inf]`);
    }
    const P = PROP[cls === 'jet' ? (sub === 'light' ? 'jet_light' : sub === 'airliner' ? 'airliner' : 'jet_biz') : cls === 'ultralight' ? 'single_hw' : cls] || PROP.single_lw;
    const tt = t || stand;
    d = { type: t, name: t ? (ACD[t] ? ACD[t][8] : t) : (cat ? `Unknown type (${cat} ${CATEGORY[cat] || ''})`.replace(/ \)/, ')') : 'Unknown type'),
      cls, sub, engines: a.n || 1, engType: a.eng || null, L: a.L, span: a.span, H: a.H, rotor: null, mtow_kg: a.mtow,
      gearKind: TAIL_WHEEL.has(tt) ? 'tail' : 'tricycle', retract: RETRACT.has(tt) || cls === 'jet' || (cls === 'turboprop'), tail: V_TAIL.has(tt) ? 'V' : T_TAIL.has(tt) ? 'T' : 'conv',
      src: stand ? 'inf' : 'obs', basis: stand ? prov.join('; ') : `FAA ACD row ${a.row} (${a.name}): L, span, H, MTOW [obs]; layout by class rule [inf]` };
    if (tt === 'PC12') { d.track = PC12_GEAR.track; prov.push(PC12_GEAR.basis); }
    finish(d, P);
    if (tt === 'PC12') { d.xNose = r3(d.xMain - PC12_GEAR.wheelbase); }
    d.dimSrc = { L: stand ? 'inf' : 'obs', span: stand ? 'inf' : 'obs', H: stand ? 'inf' : 'obs', rotor: null, track: tt === 'PC12' ? 'obs' : 'inf', proportions: 'inf' };
    prov.push('gear / wing / tail layout and proportions by class rule [inf]');
  }
  d.category = cat; d.provenance = prov; d.clsSrc = C.src;
  if (!(d.L > 0) || !(d.span > 0)) { d.L = d.L || 8.3; d.span = d.span || 11.0; d.H = d.H || 2.7; }
  if (!(d.H > 0)) d.H = r3(0.33 * d.L);
  Object.freeze(d);
  cache.set(key, d);
  return d;
}

// short text for a card / modelNote: what the placeholder is sized from
export function dimsNote(d) {
  if (!d) return 'no dimensions';
  if (d.cls === 'heli') return `Placeholder helicopter, rotor ${d.rotor.toFixed(1)} m (${d.basis.includes('recalled') ? 'type figures not verified' : 'default size'}) [inferred]`;
  if (d.src === 'obs') return `Placeholder sized to ${d.type} (FAA ACD: ${d.L.toFixed(1)} m long, ${d.span.toFixed(1)} m span); shape generic`;
  return `Placeholder of a ${d.cls.replace('_', ' ')} sized to a stand-in (${d.provenance[1] || d.basis}) [inferred]`;
}
